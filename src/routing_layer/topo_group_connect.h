/* topo_group_connect — выбор пиров и попытки подключения CHAT-группы.
 * Суперузел подключается ко всем суперузлам канала. Desktop/mobile — к двум;
 * без UP суперузлов резервируют два desktop, без них — два mobile. Проверки
 * старших классов продолжаются независимо от резервных связей. Роль supernode
 * не зависит от адресов; server без роли supernode и неизвестные устройства
 * автоматически не выбираются. Класс устройства берётся из подписанной записи
 * реестра или сохранённого snapshot, роль — из adm_tags локальной таблицы участников.
 * В классе сначала идут ещё не проверенные кандидаты, затем готовые повторы
 * с меньшим retry_at. При равенстве — текущий SQL-порядок: connected DESC,
 * известный RTT перед NULL, RTT ASC, node_id ASC. Обновление списка сохраняет
 * запросы/backoff известных кандидатов и применяет их новый SQL-приоритет.
 * Успех — транспортный UP; группа удерживает сессию до DOWN, обмен таблицами
 * продолжается отдельно. На класс не более двух попыток, CONNECTING: 2 s.
 * Недоступный узел повторяем через 5,10,15,20,25,30 s (дальше 30 s).
 * Первый JOIN_REJECT: 3 s, повторные: 120 s. История REJECT сохраняется через UP,
 * обновления списка/сети и сбрасывается после READY. Подтверждение локального допуска
 * снимает backoff его ожидания у живого транспорта, включая неизвестный класс bootstrap-пира.
 * Проверка списка раз в 1 s,
 * пока цель суперузлов не достигнута. При отсутствии UP-суперузлов desktop разрешён
 * только после проверки каждого суперузла; mobile разрешён после проверки desktop
 * и лишь при отсутствии UP обоих старших классов. Уже поднятые резервы сохраняются.
 * В standby новые автоматические попытки ждут burst; ручная стартует сразу.
 * READY/recovery не изменяются.
 * Планировщик владеет запросами, группа — NCD. Остановка отменяет попытки,
 * включая ручные, но сохраняет готовые сессии. Список кандидатов файловой БД читает
 * общий DB worker; запрос хранит копию channel и самостоятельный массив результата.
 * Пока READ выполняется, таймеры/имеющиеся соединения работают; новые автоматические
 * попытки ждут свежий список. Изменившийся за время READ состав требует повторной загрузки.
 * Остановка отсоединяет результат от группы; поздний callback освобождает только копии.
 * Все публичные вызовы и применение результата — в потоке uasync.
 */
#ifndef TOPO_GROUP_CONNECT_H
#define TOPO_GROUP_CONNECT_H

#include <stdint.h>
#include "topo_group.h"

struct TOPO_GROUP;
struct ETCP_CONN;

/* Включить/обновить автоматический подбор живой CHAT-группы с channel_id.
 * 0=проверка запланирована, -1=неверная группа/ошибка выделения контекста.
 * Текущие запросы сохраняются; ошибка отложенного запуска логируется отдельно. */
int  topo_group_connect_init(struct TOPO_GROUP* group);
/* Отменить запросы, таймеры, standby-wait и отложенные вызовы; освободить group->connect.
 * Если группа не stopping, её UP-пиры закрепляются до освобождения запросов. NULL допустим. */
void topo_group_connect_destroy(struct TOPO_GROUP* group);
/* Запланировать проверку изменившихся сессий. */
void topo_group_connect_changed(struct TOPO_GROUP* group);
/* 1 — исходящий JOIN должен ждать retry_at этого пира; 0 — задержки нет/ручная попытка.
 * Общая проверка для всех инициаторов; входящий JOIN задержкой не ограничивается. Только uasync. */
int topo_group_connect_defer_join(struct TOPO_GROUP* group, const uint8_t x[32]);
/* После публикации допуска снять только backoff ожидания локального членства у живого conn.
 * Проверяет допуск обоих участников; сохраняет remote REJECT. JOIN затем запускает caller.
 * group/conn заимствованы; NULL допустим. Только uasync. */
void topo_group_connect_admitted(struct TOPO_GROUP* group, struct ETCP_CONN* conn);
/* Учесть появление пира; для UP записать connected в БД. */
void topo_group_connect_on_up(struct TOPO_GROUP* group, struct ETCP_CONN* conn);
/* После удаления/пометки сессии DOWN: connected=0 в БД, закрыть запрос планировщика
 * и назначить повтор по reason (TRANSPORT_DOWN/REJECTED), даже если запрос уже завершён при UP.
 * Остальные причины удаления не назначают задержку. Только uasync; group/conn заимствованы. */
void topo_group_connect_on_down(struct TOPO_GROUP* group, struct ETCP_CONN* conn, enum topo_group_remove_reason reason);
/* Число текущих UP-пиров группы, независимо от READY. */
int  topo_group_connect_active_count(struct TOPO_GROUP* group);
/* Сбросить транспортный backoff и standby-wait после изменения сети;
 * сохранить историю/задержку REJECT, tested, UP и незавершённые запросы. Ручной режим не меняется. */
void topo_group_connect_restart(struct TOPO_GROUP* group);

/* Одна ручная попытка к ненулевому node_id != self в живой CHAT-группе.
 * Создаёт планировщик без автоподбора, если его ещё нет; проверяет членство через peer_open.
 * 0=принято/запрос уже есть, -1=ошибка. Ручная попытка обходит класс/backoff/standby,
 * но завершается по общему CONNECTING-таймауту и сама не повторяется.
 * В автоматическом режиме этот же кандидат после завершения подчиняется обычной политике. */
int  topo_group_connect_node_once(struct TOPO_GROUP* group, const uint8_t ed[32]);

#endif
