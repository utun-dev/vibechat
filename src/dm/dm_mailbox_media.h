/* Координатор хранения DM-файлов на суперузле S.
 * Получив заказ, S выбирает узел-хранилище M, просит сохранить зашифрованную копию файла,
 * сообщает получателям, откуда её скачать, и повторяет запросы до подтверждения или окончания срока.
 * После выполнения условия хранения S добивается удаления копий и очищает описание завершённого задания.
 * Саму передачу файлов обслуживает dm_media; здесь находятся таймер, выбор узла и обработка его ответов.
 *
 * Создаётся/уничтожается из dm_mailbox. Входящие команды передаёт dm_media через recv;
 * register записывает новый заказ в транзакции приёма сообщения. Задания переживают перезапуск в SQLite.
 * Обычные вызовы выполняются в uasync, register — в потоке соединения БД. SQL таймера вынесен в dm_mailbox_cycle.
 * На RW worker одна задача удерживает транзакцию между чтением и назначением; пакеты уходят после commit.
 * Пока общий переход на RW не завершён, прежний писатель выполняет те же SQL-шаги синхронно.
 *
 * Таймер просыпается раз в секунду и обрабатывает до8 заданий; очередной повтор задания — через5с.
 * На координатор приходится один незавершённый проход. Узел M должен иметь storage=yes в допущенной общей группе.
 * ID назначения сохраняется до запроса STORE и переживает смену маршрута/перезапуск.
 * После отказа по квоте новая попытка через60с: сначала другой M, затем прежний с новым ID назначения.
 * Истёкшая копия повторно не назначается. S и M могут работать на одном устройстве.
 * Ядро, БД и группы должны жить до завершения всех запросов координатора. Из C++ включать внутри extern "C".
 */
#ifndef DM_MAILBOX_MEDIA_H
#define DM_MAILBOX_MEDIA_H

#include <stdint.h>
#include <stddef.h>
#include <sqlite3.h>
struct UTUN_INSTANCE;
struct dm_mb_media;

/* Создать координатор и таймер для inst с работающими БД/uasync.
 * На RW worker общая схема уже проверена ядром; legacy соединение не требуется, SQL здесь не выполняется.
 * Сроки повтора сбрасывает первая транзакция таймера; после ошибки/FULL/OOM следующий tick повторяет её.
 * В legacy режиме таблицы проверяются и сроки сбрасываются синхронно.
 * Возвращает координатор либо NULL при ошибке; его освобождает dm_mailbox через destroy. */
struct dm_mb_media* dm_mailbox_media_create(struct UTUN_INSTANCE* inst);
/* Отменить таймер и незавершённые транзакции, освободить координатор; задания в БД сохраняются. NULL допустим. */
void dm_mailbox_media_destroy(struct dm_mb_media* media);
/* В транзакции записи db зарегистрировать заказ хранения сообщения msg/len для recipient.
 * Вызывающий заранее проверяет подпись и право S. Сохраняются хеш сообщения и неизменный список устройств.
 * SQLITE_OK=успех,AUTH=неверное сообщение/конфликт UUID,иначе код SQL-ошибки. Commit делает вызывающий. */
int dm_mailbox_media_register(sqlite3* db, const uint8_t recipient_ed[32], const uint8_t* msg, size_t len);
/* В uasync обработать ответ хранилища или подписанный факт получателя.
 * group/source берутся из проверенного пакета router; cmd/body/len — команда и её данные по dm_media.h.
 * Длины body: RECEIPT152,STORED/RESERVED41,DELETE_ACK/EXPIRED32,REJECT33 байта. На RW worker вход копируется до возврата.
 * Ответ M принимается только для сохранённых UUID/ID назначения; квитанция дополнительно проверяется подписью получателя.
 * Освобождение назначения и сброс держателя, как и запись факта с пробуждением задания, выполняются атомарно.
 * После commit может последовать пересылка RECEIPT/DELETE. Повтор STORE запрашивает состояние прежнего назначения.
 * Завершение хранения повторяет DELETE до16 активным M за проход. Истёкшее назначение закрывает таймер,
 * в том числе при недоступном M. Описание задания очищается после закрытия всех назначений. */
void dm_mailbox_media_recv(struct dm_mb_media* media, uint64_t group, const uint8_t source[32],
                            uint8_t cmd, const uint8_t* body, size_t len);
/* В uasync попытаться переслать152-байтовую receipt доступным суперузлам общих групп, без SQL.
 * Вызывающий уже проверил/подписал квитанцию и зафиксировал её в БД; повторной проверки здесь нет.
 * Автор и получатель исключаются; локальный суперузел допускается. Сам вызов очередь повторов не создаёт:
 * повторную доставку обеспечивает сохранённая квитанция в dm_files/dm_media_jobs.
 * Роли/допуск читаются из подтверждённого RAM-снимка. Остановка координатора прекращает оставшиеся отправки. */
void dm_mailbox_media_receipt(struct UTUN_INSTANCE* inst, const uint8_t* receipt);

#endif
