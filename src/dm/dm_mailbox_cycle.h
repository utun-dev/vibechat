/* Работа с БД для фоновой доставки и очистки файлов личных сообщений.
 * Суперузел S координирует доставку, а узел-хранилище M держит зашифрованную копию файла.
 * Модуль находит одно задание, которое пора обработать: назначить хранилище, повторить доставку,
 * учесть скачивание/открытие получателем или освободить копию после окончания срока хранения.
 * Результат содержит данные для OFFER, STORE, DELETE и уведомлений об исчезнувших копиях.
 *
 * Здесь сосредоточены SQL-операции таймера dm_mailbox_media, чтобы выполнять их в DB worker.
 * Текущую доступность узлов проверяет dm_mailbox_media в uasync; он же отправляет подготовленные данные в сеть.
 *
 * Порядок использования для одного задания:
 * 1. Открыть транзакцию записи. Обнулить cycle, задать self/now и вызвать read в worker.
 *    Для первого прохода после запуска задать reset_retry=1: все сохранённые задания станут готовы к повтору.
 * 2. Если needs_holder=1, выбрать доступный узел из candidates в uasync и скопировать ключ в holder_ed и выставить chosen.
 * 3. При выбранном chosen вызвать assign в worker, продолжая ту же транзакцию.
 * 4. После успешного commit отправить пакеты по данным cycle, затем вызвать clear.
 * При ошибке caller откатывает транзакцию и вызывает clear без отправки пакетов.
 * Read также меняет БД: назначает срок повтора, фиксирует завершение хранения и выполняет очистку.
 */
#ifndef UTUN_DM_MAILBOX_CYCLE_H
#define UTUN_DM_MAILBOX_CYCLE_H
#include "dm_media.h"
#include "dm_protocol.h"

struct dm_cycle_candidate {
    char group[65];             /* Общая группа S и возможного хранилища M. */
    uint8_t ed[32];              /* Ed25519 возможного хранилища. */
    int retry;                 /* 0=новый M,1=повторная попытка на M, ранее отказавшем по квоте. */
};
struct dm_cycle_holder {
    uint8_t ed[32];              /* Ed25519 хранилища для DELETE. */
    uint8_t assignment[16];    /* Неизменяемый ID назначения для DELETE. */
};
struct dm_cycle_notice {
    uint8_t peer[32];           /* Ed25519 устройства, которому нужно сообщить об исчезновении копии. */
    uint8_t holder_ed[32];      /* Полный ключ хранилища, чья копия удалена или просрочена. */
};
struct dm_mailbox_cycle {
    uint8_t self[32];          /* Вход read: Ed25519 суперузла S. */
    uint64_t now;              /* Вход read: текущее время в секундах с учётом NTP. */
    int reset_retry;           /* Вход read:1=сбросить сроки повтора после запуска; caller снимает флаг после commit. */
    int chosen;               /* Вход assign: caller записал выбранный ключ в holder_ed. */
    uint64_t expires;          /* Абсолютный срок хранения копии на M;0=ещё не согласован. */
    uint8_t id[16];            /* UUID файла. */
    uint8_t author_ed[32], recipient_ed[32], holder_ed[32]; /* Адреса исходящего OFFER/STORE. */
    int have_holder;           /* В БД сохранено назначение для holder_ed. */
    uint8_t assignment[16];    /* ID сохранённого либо вновь созданного назначения на M. */
    uint8_t hash[32];          /* SHA256 исходного сообщения, сохраняется и после очистки body. */
    uint8_t receipt[DM_MEDIA_RECEIPT_SIZE]; /* Подписанный факт завершения хранения. */
    uint8_t body[DM_BODY_MAX];  /* Собственная копия подписанного сообщения с описанием файла. */
    size_t size;              /* Число байтов в body. */
    int found;                /* Read нашёл задание, которому пора повторить обработку. */
    int delivered;            /* В задании уже был терминальный факт: политика хранения выполнена. */
    int stored;               /* M подтвердил сохранение зашифрованной копии. */
    int expired;              /* Срок хранения задания истёк, новую копию больше не назначаем. */
    int released;             /* Состояние назначения:0=активно,1=удалено,2=TTL,3=отказ по квоте. */
    int policy;               /* -1=не согласована,0=ждать скачивания всеми,1=ждать открытия получателем. */
    int needs_holder;         /* Caller должен выбрать доступный M. */
    int retained;             /* В этом проходе записано выполнение политики хранения. */
    int deadline;             /* В этом проходе закрыто истёкшее назначение. */
    int removed;              /* В этом проходе из БД удалено ненужное body задания. */
    int assigned;             /* Assign закрепил новое назначение на chosen. */
    int invalid;              /* Описание файла повреждено; повтор отложен, OFFER/STORE отправлять нельзя. */
    uint8_t target_ed[DM_TARGET_MAX][32]; /* Устройства, ещё не подтвердившие скачивание. */
    size_t target_count;      /* Число элементов target_ed. */
    struct dm_cycle_holder holders[16]; /* До16 назначений для одной пачки DELETE. */
    size_t holder_count;      /* Число элементов holders. */
    uint8_t facts[2 * DM_TARGET_MAX][DM_MEDIA_RECEIPT_SIZE]; /* Факты скачивания/открытия для DELETE. */
    size_t fact_count;        /* Число элементов facts. */
    struct dm_cycle_candidate* candidates; /* Собственный массив возможных хранилищ из БД. */
    size_t candidate_count;   /* Число элементов candidates. */
    size_t candidate_capacity; /* Выделенное число элементов; обслуживается модулем. */
    struct dm_cycle_notice* notices; /* Собственный массив уведомлений об исчезнувших копиях. */
    size_t notice_count;      /* Число элементов notices. */
    size_t notice_capacity;   /* Выделенное число элементов; обслуживается модулем. */
};

/* SQL для общей операции освобождения: индекс0=отказ по квоте,1=истечение срока.
 * Обновляются запись назначения (holder) и само задание (job) в одной транзакции.
 * Caller связывает ?1=UUID файла,?2=Ed25519 M,?3=ID назначения; для отказа также ?4=время следующей попытки. */
extern const char* const dm_media_release_holder_sql[2];
extern const char* const dm_media_release_job_sql[2];
/* В открытой транзакции записи выбрать одно готовое к обработке задание и заполнить cycle.
 * Меняет срок повтора, учитывает политику/срок хранения, подготавливает данные для отправки и очистки.
 * db — соединение вызывающего потока, cycle — обнулённая структура с заполненными self/now.
 * SQLITE_OK и found=0: работы нет; SQLITE_OK и found=1: результат готов к следующему шагу/commit.
 * При ошибке возвращает код SQLite, caller делает rollback и clear. SQL statements всегда закрыты. */
int dm_mailbox_cycle_read(sqlite3* db, struct dm_mailbox_cycle* cycle);
/* После read в той же транзакции закрепить выбранное хранилище и создать случайный ID назначения.
 * db — то же соединение; cycle должен иметь needs_holder=1 и chosen!=0.
 * SQLITE_OK: назначение подготовлено, отправлять STORE можно после commit; иначе код ошибки SQLite/криптографии. */
int dm_mailbox_cycle_assign(sqlite3* db, struct dm_mailbox_cycle* cycle);
/* Освободить массивы candidates/notices и обнулить всю структуру; вызывать после успеха и после ошибки. NULL допустим. */
void dm_mailbox_cycle_clear(struct dm_mailbox_cycle* cycle);
#endif
