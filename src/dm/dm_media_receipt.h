/* Подтверждения скачивания и открытия файлов личных сообщений.
 * Устройство подписывает факт FILE_RECEIVED («скачал») или TAKEN («открыл»).
 * Модуль проверяет такие факты, сохраняет их по устройствам и определяет, выполнено ли условие удаления копии:
 * файл скачали все получатели либо его открыл хотя бы один получатель.
 * Список устройств закрепляется при создании вложения и не меняется вместе с составом группы устройств.
 *
 * Порядок записи: targets_seed создаёт список адресатов, receipt_save записывает проверенный факт,
 * retention_done проверяет условие хранения. Эти функции работают с переданной SQLite в потоке владельца соединения;
 * транзакцию открывает и завершает вызывающий код. Receipt_make_read подписывает факт по копиям ключей в DB worker;
 * instance-вариант receipt_make предназначен для ещё синхронных uasync-вызовов.
 * Targets_restore восстанавливает данные при запуске. Передачей и удалением файлов управляет dm_media. */
#ifndef UTUN_DM_MEDIA_RECEIPT_H
#define UTUN_DM_MEDIA_RECEIPT_H
#include "dm_media.h"
#include <sqlite3.h>

/* Определить вид152-байтовой квитанции r:0=скачан,1=открыт,-1=неизвестный формат. Подпись здесь не проверяется. */
int dm_media_receipt_kind(const uint8_t* r);
/* В uasync подписать локальным устройством факт для сообщения body длиной len с описанием файла.
 * taken=0 означает скачивание,1 — открытие. Автор себе квитанцию не выдаёт; открытие подтверждает сторона получателя.
 * out должен вмещать152 байта. Возврат0=подписано,-1=ошибка. */
int dm_media_receipt_make(struct UTUN_INSTANCE* inst, const uint8_t* body, size_t len, int taken, uint8_t* out);
/* SQL-owner: проверить body/len и подписать локальный факт копией Ed25519-секрета signing_key[32] устройства self.
 * taken=0 — скачивание,1 — открытие; out вмещает152 байта и меняется только при успехе.
 * SQLITE_OK либо положительный код SQL/проверки/crypto. Только чтение БД, без runtime; транзакция принадлежит caller. */
int dm_media_receipt_make_read(sqlite3* db, const uint8_t self_ed[32], const uint8_t signing_key[32],
    const uint8_t* body, size_t len, int taken, uint8_t* out);
/* В транзакции записи создать неизменяемый список устройств файла, исключив автора с уже имеющимся оригиналом.
 * db — соединение вызывающего потока; body/len — уже проверенное подписанное сообщение.
 * Для DEVICE адресат задан recipient; для GROUPS устройства берутся из подписанного списка сообщения.
 * SQLITE_OK=успех,SQLITE_AUTH=недопустимое сообщение,иначе код SQL-ошибки. Commit/rollback делает вызывающий. */
int dm_media_targets_seed(sqlite3* db, const uint8_t* body, size_t len, const uint8_t recipient[32]);
/* Проверить подпись и соответствие квитанции r сообщению body/len, затем записать факт устройству из списка файла.
 * Вызывать с db в транзакции записи после targets_seed. SQLITE_OK=успех,AUTH=отказ,иначе код SQL-ошибки.
 * Функция закрывает свои SQL-запросы; commit/rollback остаются у вызывающего. */
int dm_media_receipt_save(sqlite3* db, const uint8_t* r, const uint8_t* body, size_t len);
/* Проверить условие хранения файла id в переданной db: policy=0 — скачали все получатели,1 — хотя бы один открыл.
 * done обязателен:1=условие выполнено,0=ещё нет; при ошибке тоже0. Устройства стороны автора условие не меняют.
 * SQLITE_OK=успешное чтение,NOTFOUND=нет списка получателей,иначе код SQL-ошибки. Транзакция — у вызывающего. */
int dm_media_retention_done(sqlite3* db, const uint8_t id[16], int policy, int* done);
/* В uasync при запуске восстановить списки устройств и факты скачивания из сохранённых вложений inst.
 * Выполняет одну транзакцию; исходные сообщения и подписи сохраняются. Возврат0=успех,-1=ошибка. */
int dm_media_targets_restore(struct UTUN_INSTANCE* inst);
/* SQL-only в caller WRITE: восстановить targets и receipt из сохранённых тел. SQLITE_OK/положительный SQLite code. */
int dm_media_targets_restore_write(sqlite3* db);
#endif
