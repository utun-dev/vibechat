/* stream_optimizer — автоматический выбор узлов, от которых получать части трансляции.
 * Проверяет поставщиков, сравнивает задержку и переносит выдачи на лучший доступный путь; при необходимости просит relay.
 * Явные фазы: bootstrap до первой пачки/полного KEY media, live, catchup сверх заданного content lag, recovery,
 * waiting без маршрута/DATA, draining подписанного END, finished после общего курсора. Смена фаз логируется.
 * Обычная оптимизация допускается только в live/catchup; поиск недостающих частей и OVERLOAD работают независимо.
 * Пауза DATA отдельной части (stream_stall_timeout_ms, default500) запускает точные INFO к трём резервам.
 * Выбор через50мс после первого пригодного ответа; старая выдача сохраняется до подтверждённого DATA восстановления.
 * Одна аварийная замена живёт не дольше max(5с,stall_timeout,4*RTT) от выбора; срок фиксирован, DATA его не продлевают.
 * Молчание ограничивается отдельно max(stall_timeout,4*RTT); неудача включает backoff данного резерва до30с.
 * До трёх резервов проверяются INFO каждые5с+jitter в обычном бюджете; постоянных дублирующих DATA нет.
 * После двух приоритетных проверок гарантирован шаг полного обзора; recovery не сбрасывает его прогресс.
 * При близких score учитывает все промежуточные узлы путей; protected_by_fec проверяет оставшиеся k частей после отказа любого из них.
 * Общий автор исключён из этой оценки, общие физические каналы по node_id определить нельзя; r=0 остаётся без FEC-защиты.
 * Обычный перенос сначала подтверждает точную DATA и догон, затем сравнивает приход одного будущего индекса обоих поставщиков.
 * Если новая DATA позже старой больше score_hysteresis_ms, перекрытие отменяется; сброс базы lag не считается улучшением.
 * Score учитывает очередь, нехватку нужной позиции, историю проблем и дефицит receive/source rate; связанные штрафы не складываются.
 * Для обычного переноса INFO текущего пути обновляется до возраста<=5с; готовность нового пути всё равно подтверждают DATA.
 * Известная PTS автора минус последнее полное локальное видео задаёт подтверждённый content lag; часы ожидания его не растят.
 * Превышение stream_max_live_lag_ms (default10000) подтверждается1с: переход с GAP требует свежего полного KEY на k разных частях.
 * Без общего KEY сохраняет DATA и обновляет INFO; повторный скачок не чаще max(limit,5с) и только на более новый KEY.
 * Существующие выдачи переходят через SEEK в тех же слотах, даже при закрытом новом допуске; уже принятые части KEY сохраняются.
 * Вытеснение нужной истории использует тот же общий KEY/SEEK, включая проверку наличия полного диапазона на k частях.
 * Пауза автора не отменяет частый поиск резервов; сама по себе она не вызывает новые DATA-подписки или GAP.
 * OVERLOAD переносит выбранные необходимые выдачи без minimum_hold; старая сохраняется до точной DATA и догона курсора.
 * completed/drained отменяет перенос сразу; expired оставляет до5с суммарно от начала переноса, включая повторные попытки.
 * Пауза самой DATA продолжает обычное аварийное восстановление; полезная старая выдача остаётся при неудаче замены.
 * Внутренний модуль stream: create для одной трансляции → tick при сетевом событии/по таймеру → destroy.
 * Все вызовы — uasync. Планировщик общий для локальных читателей; destroy отменяет принадлежащие ему пробы и выдачи. */
#ifndef STREAM_OPTIMIZER_H
#define STREAM_OPTIMIZER_H

#include "stream.h"

struct stream_optimizer;
struct stream_receive_info;

// ── Оценка поставщиков и расписание проб ──

/* Меньше лучше: chain RTT + 2*peer RTT + 3мс*path.count + штраф0..1000мс + возраст INFO(1мс/с, до60мс).
 * Штраф — максимум истории проблем, возраста очереди, PTS-отставания при нехватке нужной позиции
 * и дефицита receive/source rate >=10% при >=20 блоках. Свежая нужная часть partial relay не требует полного видео.
 * Скорости характеризуют полученную историю, не гарантируют новый последний переход; перенос проверяет реальные DATA.
 * now_ms — локальные монотонные мс; неизвестный RTT даёт UINT64_MAX, отсутствующая метрика не считается подтверждённым дефектом.
 * info/metrics обязательны даже при valid=0; valid=0 отключает только штраф метрики.
 * Текущая остановка/lag>500мс дают штраф1000; иначе доля late плюс10мс при наличии прежних остановок. */
uint64_t stream_supplier_score(const struct stream_receive_info *info, const struct stream_metric_snapshot *metrics, int valid, uint64_t now_ms);

/* Только монотонное расписание; pending/active — незавершённый обход/пробы текущего цикла.
 * Возвращает допустимое число новых узлов, не адресов/субпотоков: 32 один раз, затем 0/1. */
struct stream_probe_schedule {
    uint64_t cycle;      // Номер цикла; нулевая структура получает первый burst32.
    uint64_t started_ms; // Начало цикла; новый цикл через >=30с, только без pending/active.
    uint64_t next_ms;    // Следующий допуск одного узла, не раньше чем через1с после предыдущего tick.
};
unsigned stream_probe_schedule_tick(struct stream_probe_schedule *schedule, uint64_t now_ms, unsigned pending, unsigned active);

// ── Жизненный цикл планировщика ──

/* Скопировать заранее проверенный descriptor, выделить n слотов и поставить bootstrap timer100мс.
 * inst/ua живут до destroy, *out заранее NULL; STREAM_OK/ERR_ARGUMENT/ERR_MEMORY, out не меняется при отказе. */
int stream_optimizer_create(struct UTUN_INSTANCE *inst, const struct stream_descriptor *descriptor, struct stream_optimizer **out);

// Остановить пробы/выдачи и освободить планировщик; NULL допустим, instance ещё должен быть жив.
void stream_optimizer_destroy(struct stream_optimizer *optimizer);

/* Освободить пробы, DATA и постоянные слоты для ожидания маршрута. Сохранить статистику и consumer/media cursors.
 * Владелец не вызывает tick до возвращения BGP; следующий tick заново проверяет предложения и недостающую позицию. */
void stream_optimizer_suspend(struct stream_optimizer *optimizer);

// ── Выбор поставщиков и настройки ──

/* Проход для живой подписки: roster/INFO, выбор всех n частей, перенос с перекрытием и recovery.
 * now_ms — монотонные мс. Отдельный таймер соблюдает сроки паузы/выбора независимо от общего100-мс tick.
 * После5с без полной пачки обновляются предложения; аварийные выдачи сохраняются, недоступная история требует общего KEY.
 * Первый пригодный INFO задаёт старт; отсутствие победителя100мс запускает relay-помощь.
 * Новые DATA выдачи дополняют старт; обычная оценка/миграция ждёт первую проверенную пачку, для media — полный KEY.
 * При дефиците DATA отказ accepting=0 повторно проверяется через1с+jitter в обычном бюджете проб этой трансляции.
 * INFO проверяет точную позицию; нормальный перенос получает свежий INFO до SUBSCRIBE, который повторно проверяет допуск.
 * Отказ POSITION/EXPIRED ограничивает повтор той же позиции; новый KEY не наследует её штраф.
 * END снимает выдачи только после дочитывания последней пачки. Owner/cursors принадлежат общей stream-session. */
void stream_optimizer_tick(struct stream_optimizer *optimizer, struct STREAM_HANDLE *subscription, uint64_t now_ms);

// Скопировать пороги подтверждения, удержания и гистерезиса в мс (каждый <=60000); STREAM_OK/STREAM_ERR_ARGUMENT.
int stream_optimizer_configure(struct stream_optimizer *optimizer, const struct stream_selection_settings *settings);

// Скопировать статистику; optimizer и info обязательны.
void stream_optimizer_info(struct stream_optimizer *optimizer, struct stream_selection_info *info);

// ── Уведомления от Merkle/BGP и relay ──

// Merkle/BGP ускоряет сверку roster; здоровые DATA сохраняются, возвращённый кандидат получает свежий INFO без старого backoff.
void stream_optimizer_roster_changed(struct stream_optimizer *optimizer, struct stream_address peer);

// Подтверждённая помощь немедленно обновляет кандидатов и снимает старый backoff конкретного пира.
void stream_optimizer_refresh(struct stream_optimizer *optimizer, struct stream_address peer);

#endif
